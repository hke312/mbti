/**
 * 각 성격 유형을 대표하는 3D 동물 캐릭터 정보입니다.
 */
export interface MbtiCharacter {
  /** 캐릭터 동물 종류 (예: "부엉이") */
  animal: string;
  /** 동물에 어울리는 캐릭터 이름 (예: "부엉 선장") */
  name: string;
}

/**
 * MBTI 유형 1개에 들어가는 전체 설명 데이터 구조입니다.
 */
export interface MbtiTypeInfo {
  /** 4글자 유형 코드 */
  code: MbtiTypeCode;
  /** 유형의 매력을 담은 한글 별명 */
  nickname: string;
  /** 한눈에 읽히는 한 줄 소개 */
  summary: string;
  /** 성격 특징을 풀어낸 3~4문장 설명 */
  description: string;
  /** 대표적인 강점 3가지 */
  strengths: [string, string, string];
  /** 살피면 좋은 조심할 점 2가지 */
  cautions: [string, string];
  /** 특히 잘 어울리는 궁합 유형 2가지 */
  bestMatches: [MbtiTypeCode, MbtiTypeCode];
  /** 파스텔 톤의 대표 색상 (HEX 코드) */
  color: string;
  /** 유형별 동물 캐릭터 정보 */
  character: MbtiCharacter;
}

